"""The large-signal tier and the enable ramp.

The load-step droop and the unload overshoot are replayed as an ODE of the model's OWN network,
so the ground truth here is generated by that same forward model with KNOWN `iaG`, `iaV` and
`ovVdz` -- which is exactly the question a port has to answer: does the fit still invert the
forward model it was written for, on this new data contract?

Nothing in `pmukit/fit/` may launch a process, and nothing here does.
"""
import numpy as np
import pytest

from pmukit.config import DerivedConfig
from pmukit.fit import en, load_en, zout
from tests.test_fit_common import CELL, CELL_NOLOAD, RAIL, TEMPS, make, rel, zparams

TIME = np.linspace(0.0, 2e-6, 401)
ZTRUE = zparams(Ra=0.2, La=2e-6, Rpl=40.0, Cout=1e-10, esr=0.2)
VREG, I_OFF, I_ON = 0.8, 2e-6, 5e-3
IAG, IAV, OVVDZ = 3.0e-3, 0.28, 0.020
T0, EDGE = 0.2e-6, 1e-9

DERIVED = DerivedConfig(
    supply={"nominal_v": 1.05},
    rails={RAIL: {}},
    loads={RAIL: {"events": [
        {"event": "tran_load_on", "from_a": I_OFF, "to_a": I_ON, "edge_s": EDGE},
        {"event": "tran_load_off", "from_a": I_ON, "to_a": I_OFF, "edge_s": EDGE}]}})


def wave(i_from, i_to, discharge=None):
    secs = zout.sections_of(ZTRUE)
    sol = load_en.rail_trace(ZTRUE["Ra"], secs, ZTRUE["Cout"], i_from, i_to, IAG, IAV, VREG,
                             T0, EDGE, float(TIME[-1] - T0), discharge=discharge, t_eval=TIME)
    return np.asarray(sol.y[len(secs)], float)


def build(tmp_path, with_unload=True):
    ds = make(tmp_path)
    from tests.test_fit_common import FREQ, declare_ac
    declare_ac(ds, f"ac_zout.{RAIL}", unit="ohm")
    ds.put(f"ac_zout.{RAIL}", CELL, zout.predict(ZTRUE, f=FREQ))
    ds.declare(f"tran_load_on.{RAIL}", dims=("process", "temp_c", "vset", "time_s"),
               dtype="float64", unit="V", coord=TIME)
    ds.put(f"tran_load_on.{RAIL}", CELL_NOLOAD, wave(I_OFF, I_ON))
    if with_unload:
        ds.declare(f"tran_load_off.{RAIL}", dims=("process", "temp_c", "vset", "time_s"),
                   dtype="float64", unit="V", coord=TIME)
        ds.put(f"tran_load_off.{RAIL}", CELL_NOLOAD,
               wave(I_ON, I_OFF, discharge={"ovVdz": OVVDZ}))
    return ds


# --------------------------------------------------------------------------- the assist


def test_the_assist_is_odd_with_zero_slope_at_the_operating_point():
    """`i_assist = iaG*tanh(verr*|verr|/iaV^2)` is ODD with `f'(0) = 0` EXACTLY, which is why
    Zout, PSRR and noise are untouched by it at the operating point."""
    def assist(verr):
        return IAG * np.tanh(verr * abs(verr) / (IAV * IAV))
    for v in (1e-6, 1e-4, 1e-2, 0.1):
        assert assist(-v) == pytest.approx(-assist(v), rel=1e-12)
    h = 1e-9
    assert abs((assist(h) - assist(-h)) / (2 * h)) < 1e-9      # zero slope at the OP


def test_droop_fit_reproduces_the_measured_dip(tmp_path):
    ds = build(tmp_path)
    bf = load_en.fit(ds, RAIL, CELL, DERIVED, zout_params=ZTRUE)
    assert not bf.missing
    assert bf.score < 2.0, bf.notes                            # % error on the droop
    assert bf.metric == "load-step droop % error"
    # one characterized event cannot separate the two assist parameters, and the block must
    # SAY so instead of presenting iaV as a measurement
    assert any("partly degenerate" in n for n in bf.notes)
    assert "iaV" in bf.identifiability["unidentifiable"]
    assert 0.5 * IAG < bf.params["iaG"] < 2.0 * IAG


def test_assist_matches_every_amplitude_and_generalizes_to_a_held_out_one():
    """With more than one step amplitude the two-parameter search runs, and it is gated on the
    DROOPS and on a held-out amplitude -- NOT on the parameter values.

    That is deliberate and documented: `(iaG, iaV)` are partly degenerate, a whole valley
    reproduces the same droops, and the tie-break takes the SMALLEST `iaG` in that valley (the
    gentlest assist that explains the data).  Asserting the planted pair here would be asserting
    the tie-break's position along a valley, which is not what the block claims to measure.
    """
    secs = zout.sections_of(ZTRUE)
    dips = {}
    for i_to in (1e-3, 3e-3, 5e-3):
        dips[(I_OFF, i_to)] = load_en.predict_dip(
            ZTRUE["Ra"], secs, ZTRUE["Cout"], I_OFF, i_to, IAG, IAV, VREG,
            t0=T0, edge=EDGE, tstop=float(TIME[-1] - T0)) * 1e-3
    res = load_en.fit_assist(ZTRUE["Ra"], secs, ZTRUE["Cout"], dips, VREG,
                             t0=T0, edge=EDGE, tstop=float(TIME[-1] - T0))
    assert res is not None
    assert res["_diag"]["single_event"] is False
    assert res["_diag"]["rms_mV"] < 2.0, res["_diag"]
    assert res["_diag"]["held_out"] is not None
    assert abs(res["_diag"]["held_out"]["err_pct"]) < 5.0
    # the fitted pair reproduces the planted droops, which is the claim the block makes
    for (frm, to), dip in dips.items():
        got = load_en.predict_dip(ZTRUE["Ra"], secs, ZTRUE["Cout"], frm, to,
                                  res["iaG"], res["iaV"], VREG,
                                  t0=T0, edge=EDGE, tstop=float(TIME[-1] - T0))
        assert abs(got - dip * 1e3) < 2.5


