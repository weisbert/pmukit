def test_en_ramp_recovers_delay_rise_and_overshoot(tmp_path):
    td, tr, over = 1e-6, 2e-6, 0.04 * VREG
    grid = np.linspace(0.0, 1e-5, 301)
    truth = {"t_delay": td, "t_rise": tr, "v_overshoot": over}
    ds = make(tmp_path)
    ds.declare(f"tran_en.{RAIL}", dims=("process", "temp_c", "vset", "time_s"),
               dtype="float64", unit="V", coord=grid)
    ds.put(f"tran_en.{RAIL}", CELL_NOLOAD, en.predict(truth, t=grid, final=VREG, start=0.0))

    bf = en.fit(ds, RAIL, CELL_NOLOAD, DERIVED)
    assert not bf.missing
    assert bf.score < 1.0, bf.notes
    assert rel(bf.params["t_delay"], td) < 0.05
    assert rel(bf.params["t_rise"], tr) < 0.05
    assert rel(bf.params["v_overshoot"], over) < 0.10
    assert bf.params["i_rise"] is None and bf.params["i_overshoot"] is None
    assert any("NOT signed off" in n for n in bf.notes)


def test_en_ramp_of_a_bias_fills_the_current_fields(tmp_path):
    grid = np.linspace(0.0, 1e-5, 301)
    truth = {"t_delay": 5e-7, "i_rise": 1e-6, "i_overshoot": 0.0}
    ds = make(tmp_path)
    ds.declare("tran_en.IB_PTAT", dims=("process", "temp_c", "vset", "time_s"),
               dtype="float64", unit="A", coord=grid)
    ds.put("tran_en.IB_PTAT", CELL_NOLOAD,
           en.predict(truth, t=grid, final=5e-7, start=0.0))
    bf = en.fit(ds, "IB_PTAT", CELL_NOLOAD,
                DerivedConfig(biases={"IB_PTAT": {"vcomp_v": 0.4}}))
    assert bf.params["i_rise"] is not None
    assert bf.params["t_rise"] is None and bf.params["v_overshoot"] is None
    assert rel(bf.params["i_rise"], truth["i_rise"]) < 0.10


def test_en_cell_is_per_corner_and_temperature(tmp_path):
    grid = np.linspace(0.0, 1e-5, 301)
    ds = make(tmp_path)
    ds.declare(f"tran_en.{RAIL}", dims=("process", "temp_c", "vset", "time_s"),
               dtype="float64", unit="V", coord=grid)
    for T in TEMPS:
        ds.put(f"tran_en.{RAIL}", dict(CELL_NOLOAD, temp_c=T),
               en.predict({"t_delay": 1e-6, "t_rise": 2e-6, "v_overshoot": 0.0},
                          t=grid, final=VREG, start=0.0))
    bf = en.fit(ds, RAIL, dict(CELL_NOLOAD, temp_c=125.0), DERIVED)
    assert bf.cell == {"process": "tt", "temp_c": 125.0}
