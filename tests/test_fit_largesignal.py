def test_the_discharge_gate_has_zero_value_and_zero_slope_at_the_operating_point():
    """The one-sided deadzone gate is what keeps Zout, PSRR and noise bit-identical: below the
    deadzone it contributes neither value nor slope."""
    secs = zout.sections_of(ZTRUE)
    quiet = load_en.predict_overshoot(ZTRUE["Ra"], secs, ZTRUE["Cout"], I_ON, I_OFF,
                                      ovVdz=10.0, iaG=IAG, iaV=IAV, vreg=VREG,
                                      t0=T0, edge=EDGE, tstop=float(TIME[-1] - T0))
    engaged = load_en.predict_overshoot(ZTRUE["Ra"], secs, ZTRUE["Cout"], I_ON, I_OFF,
                                        ovVdz=OVVDZ, iaG=IAG, iaV=IAV, vreg=VREG,
                                        t0=T0, edge=EDGE, tstop=float(TIME[-1] - T0))
    assert engaged < quiet                       # a deadzone above every excursion is inert


def test_overshoot_peak_is_monotone_in_the_deadzone():
    """Monotonicity is what makes the deadzone invertible against a measured overshoot."""
    secs = zout.sections_of(ZTRUE)
    peaks = [load_en.predict_overshoot(ZTRUE["Ra"], secs, ZTRUE["Cout"], I_ON, I_OFF, v,
                                       iaG=IAG, iaV=IAV, vreg=VREG, t0=T0, edge=EDGE,
                                       tstop=float(TIME[-1] - T0))
             for v in (2e-3, 8e-3, 2e-2, 5e-2)]
    assert peaks == sorted(peaks)


def test_direction_comes_from_the_declared_currents_not_a_label(tmp_path):
    """A plan whose `tran_load_on` event declares a DECREASING current is a direction the
    fitter must read from `sign(to_a - from_a)`, never from the label."""
    ds = build(tmp_path, with_unload=False)
    bad = DerivedConfig(supply={"nominal_v": 1.05}, rails={RAIL: {}},
                        loads={RAIL: {"events": [{"event": "tran_load_on", "from_a": I_ON,
                                                  "to_a": I_OFF, "edge_s": EDGE}]}})
    bf = load_en.fit(ds, RAIL, CELL, bad, zout_params=ZTRUE)
    assert any("DIRECTION is taken from sign(to_a - from_a)" in n for n in bf.notes)


def test_predict_replays_the_waveform_without_a_simulator(tmp_path):
    ds = build(tmp_path)
    bf = load_en.fit(ds, RAIL, CELL, DERIVED, zout_params=ZTRUE)
    gt = wave(I_OFF, I_ON)
    model = load_en.predict(bf.params, t=TIME, zout=ZTRUE, i_from=I_OFF, i_to=I_ON,
                            vreg=VREG, edge=EDGE, t0=T0)
    assert model.shape == TIME.shape
    # the droop the fit was scored on is reproduced by predict to the same tolerance
    assert rel(VREG - model.min(), VREG - gt.min()) < 0.05


